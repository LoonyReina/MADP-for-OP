def completed_gate_retry_seconds(
    config: DaemonConfig | None,
    role: str,
) -> int:
    """Keep notifier retries behind the scheduler's stale-board fence."""
    policy = config.policy if config else {}
    if role == "tester":
        retry_key = "tester_completed_without_evidence_retry_seconds"
        board_key = "tester_board_stale_seconds"
    else:
        retry_key = "solver_completed_without_progress_retry_seconds"
        board_key = "solver_board_stale_seconds"
    try:
        board_seconds = int(policy.get(board_key, 300) or 300)
    except (TypeError, ValueError):
        board_seconds = 300
    try:
        retry_seconds = int(policy.get(retry_key, board_seconds) or board_seconds)
    except (TypeError, ValueError):
        retry_seconds = board_seconds
    if retry_seconds <= 0:
        return 0
    return max(retry_seconds, max(0, board_seconds))


class SolverNotifier:
    def __init__(self, root: Path, config: DaemonConfig | None = None) -> None:
        self.state_dir = root / "TestUtils" / "tester_daemon"
        self.config = config

    def write(self, decisions: tuple[GateDecision, ...]) -> None:
        self.state_dir.mkdir(parents=True, exist_ok=True)
        notices = [d for d in decisions if d.action == ActionKind.NOTIFY_SOLVER]
        tester_notices = [d for d in decisions if d.action == ActionKind.NOTIFY_TESTER_CASEGEN]
        wakeups = [serialize_wakeup(notice, self.config) for notice in notices]
        tester_wakeups = [serialize_tester_wakeup(notice, self.config) for notice in tester_notices]
        semantic_signature = notifier_semantic_signature(
            self.state_dir,
            self.config,
            wakeups,
            tester_wakeups,
        )
        if notifier_outputs_are_current(self.state_dir, semantic_signature):
            return
        lines = [
            "# Solver Wakeups",
            "",
            "Generated by tester daemon shadow/advisory scan. These are notifications, not source edits.",
            "",
        ]
        if not notices:
            lines.append("- none")
        for notice in notices:
            lines.append(
                f"- {notice.row.op}: {notice.row.gate_stage}; board next command: `{notice.row.next_command}`"
            )
        lines.append("")
        (self.state_dir / "SOLVER_WAKEUPS.md").write_text("\n".join(lines), encoding="utf-8")
        self.write_machine_readable(wakeups)
        self.write_tester_casegen_plan(tester_notices)
        write_native_relay_outbox(self.state_dir.parent.parent)
        (self.state_dir / "notifier_semantic_state.json").write_text(
            json.dumps(
                {"updated_at": utc_now_iso(), "signature": semantic_signature},
                ensure_ascii=False,
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )

    def write_machine_readable(self, wakeups: list[dict[str, object]]) -> None:
        now = utc_now_iso()
        active_keys = [str(wakeup["key"]) for wakeup in wakeups]
        previous = read_json(self.state_dir / "solver_wakeup_state.json")
        previous_keys = set(previous.get("active_keys", [])) if isinstance(previous.get("active_keys"), list) else set()
        new_wakeups = [wakeup for wakeup in wakeups if str(wakeup["key"]) not in previous_keys]

        current = {
            "updated_at": now,
            "wakeups": wakeups,
            "new_wakeup_count": len(new_wakeups),
        }
        (self.state_dir / "solver_wakeups.json").write_text(
            json.dumps(current, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        state = {
            "updated_at": now,
            "active_keys": active_keys,
        }
        (self.state_dir / "solver_wakeup_state.json").write_text(
            json.dumps(state, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        self.write_trigger_plan(now, wakeups, previous_keys)
        if not new_wakeups:
            return
        with (self.state_dir / "solver_wakeups.jsonl").open("a", encoding="utf-8") as fh:
            for wakeup in new_wakeups:
                record = {
                    "time": now,
                    "event": "solver_wakeup",
                    **wakeup,
                }
                fh.write(json.dumps(record, ensure_ascii=False) + "\n")

    def write_trigger_plan(
        self,
        now: str,
        wakeups: list[dict[str, object]],
        previous_keys: set[object],
    ) -> None:
        prompt_dir = self.state_dir / "solver_trigger_prompts"
        prompt_dir.mkdir(parents=True, exist_ok=True)
        ack_state = read_trigger_ack_state(self.state_dir.parent.parent)
        sent = ack_state.get("sent", {}) if isinstance(ack_state.get("sent"), dict) else {}
        triggers: list[dict[str, object]] = []
        for wakeup in wakeups:
            key = str(wakeup["key"])
            digest = sha1(key.encode("utf-8")).hexdigest()[:12]
            prompt_path = prompt_dir / f"{wakeup['op']}_{digest}.md"
            thread_id = str(wakeup.get("thread_id", ""))
            model, thinking = relay_profile_for(self.config, str(wakeup["op"]), "solver") if self.config else ("", "")
            sent_record = sent.get(key) if isinstance(sent, dict) else None
            prompt_context = session_prompt_context(
                self.state_dir,
                self.config,
                wakeup,
                role="solver",
                sent=sent,
            )
            contract_issues = role_contract_issues(
                str(wakeup.get("solver_goal", "") or ""),
                "solver",
            )
            prompt = build_solver_prompt(wakeup, self.config, prompt_context=prompt_context)
            prompt_path.write_text(prompt, encoding="utf-8")
            record_session_prompt_observation(
                self.state_dir,
                wakeup,
                prompt_context,
                prompt,
                prompt_path,
            )
            status = "ready" if thread_id else "missing-thread-id"
            if isinstance(sent_record, dict):
                status = normalized_trigger_status(sent_record, str(sent_record.get("status", "sent") or "sent"))
                stale_seconds = completed_gate_retry_seconds(self.config, "solver")
                if status == "completed" and completed_trigger_stale(sent_record, stale_seconds, now):
                    status = "retry-ready"
                if delivery_reconciliation_pending(sent_record):
                    status = "reconcile-wait"
                elif explicit_delivery_retry_pending(sent_record, now):
                    status = "retry-wait"
                elif status == "needs-native-delivery":
                    status = "needs-native-delivery"
                elif sent_record.get("thread_status_type") == "systemError":
                    if self.config and solver_session_replacement_allowed(self.config):
                        status = "replacement-required"
                    else:
                        status = "same-session-recovery-required"
                elif sent_record.get("failure_kind") == "native_turn_no_agent_output":
                    no_agent_count = int(sent_record.get("native_no_agent_output_count", 1) or 1)
                    if no_agent_count >= 2:
                        if self.config and solver_session_replacement_allowed(self.config):
                            status = "replacement-required"
                        elif same_session_recovery_window_elapsed(sent_record, now, self.config):
                            status = "retry-ready"
                        else:
                            status = "same-session-recovery-required"
                    elif solver_retry_window_elapsed(sent_record, now, self.config):
                        status = "retry-ready"
                    else:
                        status = "retry-wait"
                if status in {"interrupted", "failed", "cancelled"}:
                    if solver_retry_window_elapsed(sent_record, now, self.config):
                        status = "retry-ready"
                    elif sent_record.get("delivery_retry_after"):
                        status = "retry-wait"
                if (
                    prompt_context.get("profile") in CONTRACT_MEMORY_PROFILES
                    and str(prompt_context.get("prompt_mode", "") or "") == "reanchor"
                    and str(sent_record.get("contract_revision", "") or "")
                    and str(sent_record.get("contract_revision", "") or "")
                    != str(prompt_context.get("contract_revision", "") or "")
                    and status != "retry-ready"
                ):
                    status = "ready"
                if (
                    str(prompt_context.get("prompt_mode", "") or "") == "correction"
                    and str(prompt_context.get("correction_reason", "") or "")
                    and str(sent_record.get("correction_reason", "") or "")
                    != str(prompt_context.get("correction_reason", "") or "")
                    and status != "retry-ready"
                ):
                    status = "ready"
            if contract_issues:
                status = "contract-invalid"
            triggers.append(
                {
                    "season": wakeup.get("season", ""),
                    "op": wakeup["op"],
                    "gate_stage": wakeup["gate_stage"],
                    "key": key,
                    "new": key not in previous_keys,
                    "thread_id": thread_id,
                    "model": model,
                    "thinking": thinking,
                    "prompt_path": relpath(prompt_path, self.state_dir.parent.parent),
                    "prompt_profile": prompt_context.get("profile", "standard-delta"),
                    "prompt_mode": prompt_context.get("prompt_mode", "delta"),
                    "delivery_ordinal": prompt_context.get("delivery_ordinal", 0),
                    "contract_revision": prompt_context.get("contract_revision", ""),
                    "reanchor_reason": prompt_context.get("reanchor_reason", ""),
                    "correction_reason": prompt_context.get("correction_reason", ""),
                    "reanchor_interval": prompt_context.get("reanchor_interval"),
                    "quality_status": prompt_context.get("quality_status", "unavailable"),
                    "quality_version": prompt_context.get("quality_version", ""),
                    "quality_depth": prompt_context.get("quality_depth", 0),
                    "contract_issues": contract_issues,
                    "prompt_chars": len(prompt),
                    "status": status,
                    "sent_at": sent_record.get("updated_at", "") if isinstance(sent_record, dict) else "",
                    "preferred_delivery": "ide_native_relay",
                    "fallback_delivery": "app_server_stdio_storage_only",
                }
            )

        payload = {
            "updated_at": now,
            "trigger_kind": "codex_thread_native_relay",
            "preferred_delivery": "ide_native_relay",
            "fallback_delivery": "app_server_stdio_storage_only",
            "triggers": triggers,
        }
        (self.state_dir / "solver_trigger_plan.json").write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        lines = [
            "# Solver Trigger Plan",
            "",
            "Generated by tester daemon. Prefer IDE-native relay for each ready prompt so solver turns are visible in the Codex pane.",
            "",
            "Monitoring policy: any delivered turn with storage/native thread evidence is recorded as IDE-visible for operator monitoring.",
            "",
        ]
        if not triggers:
            lines.append("- none")
        for trigger in triggers:
            lines.append(
                f"- {trigger['op']}: {trigger['gate_stage']} status={trigger['status']} "
                f"thread={trigger.get('thread_id') or '-'} prompt=`{trigger['prompt_path']}` "
                f"delivery={trigger['preferred_delivery']} new={trigger['new']}"
            )
        lines.append("")
        (self.state_dir / "SOLVER_TRIGGER_PLAN.md").write_text("\n".join(lines), encoding="utf-8")

