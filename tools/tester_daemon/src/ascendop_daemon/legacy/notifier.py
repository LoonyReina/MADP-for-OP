def read_json(path: Path) -> dict[str, object]:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def solver_retry_window_elapsed(
    sent_record: dict[str, object],
    now: str,
    config: DaemonConfig | None,
) -> bool:
    if app_side_relay_can_bypass_retry(sent_record):
        return True
    explicit_retry_after = parse_timestamp(str(sent_record.get("delivery_retry_after", "") or ""))
    now_ts = parse_timestamp(now)
    if explicit_retry_after is not None and now_ts is not None:
        return now_ts >= explicit_retry_after
    retry_seconds = failed_trigger_retry_seconds(sent_record, config, "solver")
    if retry_seconds <= 0:
        return True
    sent_ts = trigger_retry_anchor(sent_record)
    if now_ts is None or sent_ts is None:
        return False
    return (now_ts - sent_ts).total_seconds() >= retry_seconds


def explicit_delivery_retry_pending(sent_record: dict[str, object], now: str) -> bool:
    if app_side_relay_can_bypass_retry(sent_record):
        return False
    retry_after = parse_timestamp(str(sent_record.get("delivery_retry_after", "") or ""))
    now_ts = parse_timestamp(now)
    return retry_after is not None and now_ts is not None and now_ts < retry_after


def tester_retry_window_elapsed(
    sent_record: dict[str, object],
    now: str,
    config: DaemonConfig | None,
) -> bool:
    if app_side_relay_can_bypass_retry(sent_record):
        return True
    explicit_retry_after = parse_timestamp(str(sent_record.get("delivery_retry_after", "") or ""))
    now_ts = parse_timestamp(now)
    if explicit_retry_after is not None and now_ts is not None:
        return now_ts >= explicit_retry_after
    retry_seconds = failed_trigger_retry_seconds(sent_record, config, "tester")
    if retry_seconds <= 0:
        return True
    sent_ts = trigger_retry_anchor(sent_record)
    if now_ts is None or sent_ts is None:
        return False
    return (now_ts - sent_ts).total_seconds() >= retry_seconds


def trigger_retry_anchor(sent_record: dict[str, object]) -> datetime | None:
    """Use stable turn timing so observation polls cannot postpone retries."""
    for field in ("failure_started_at", "native_completedAt", "updated_at"):
        value = sent_record.get(field)
        if value in (None, ""):
            continue
        if field == "native_completedAt":
            try:
                return datetime.fromtimestamp(float(value), tz=timezone.utc)
            except (TypeError, ValueError, OSError):
                continue
        parsed = parse_timestamp(str(value))
        if parsed is not None:
            return parsed
    return None


def same_session_recovery_window_elapsed(
    sent_record: dict[str, object],
    now: str,
    config: DaemonConfig | None,
) -> bool:
    retry_seconds = int(
        config.policy.get("solver_same_session_recovery_retry_seconds", 300)
        if config
        else 300
    )
    anchor = trigger_retry_anchor(sent_record)
    now_ts = parse_timestamp(now)
    if anchor is None or now_ts is None:
        return False
    return (now_ts - anchor).total_seconds() >= max(0, retry_seconds)


def app_side_relay_can_bypass_retry(sent_record: dict[str, object]) -> bool:
    """Remote-control failures are daemon-channel failures, not App-side relay failures."""
    return (
        str(sent_record.get("delivery_retry_reason", "") or "") == "remote_control_not_ready"
        or str(sent_record.get("failure_kind", "") or "") == "codex_app_restart_interrupted"
    )


def failed_trigger_retry_seconds(
    sent_record: dict[str, object],
    config: DaemonConfig | None,
    role: str,
) -> int:
    if str(sent_record.get("failure_kind", "") or "") in {
        "codex_cli_process_dead_no_thread_progress",
        "codex_app_restart_interrupted",
    }:
        if config is not None:
            return int(config.policy.get("codex_cli_dead_trigger_retry_seconds", 10) or 10)
        return 10
    if role == "tester":
        if config is not None:
            return int(
                config.policy.get(
                    "tester_failed_trigger_retry_seconds",
                    config.policy.get("tester_trigger_retry_seconds", 300),
                )
                or 300
            )
        return 300
    if config is not None:
        return int(
            config.policy.get(
                "solver_failed_trigger_retry_seconds",
                config.policy.get("solver_trigger_retry_seconds", 300),
            )
            or 300
        )
    return 300


def parse_timestamp(text: str) -> datetime | None:
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        return parsed.replace(tzinfo=timezone.utc)
    return parsed


def relpath(path: Path, root: Path) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)
