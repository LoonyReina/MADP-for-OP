def pulse_event_text(wakeup: dict[str, object]) -> str:
    op = str(wakeup.get("op", ""))
    gate_stage = str(wakeup.get("gate_stage", "") or "")
    haystack = " ".join(
        str(wakeup.get(field, "") or "")
        for field in ("key", "next_command")
    )
    match = re.search(rf"\b{re.escape(op)}_V\d+(?:_\d+)?\b", haystack)
    if gate_stage == "result-exists" and "diagnostic supplement" in haystack.lower():
        version = match.group(0) if match else op
        return (
            f"{version} diagnostics are now available in RESULT_DIAGNOSTIC.md; "
            "rerun the live board and use its exact command, log path, and first failing line."
        )
    if gate_stage == "result-exists" and match:
        return f"{match.group(0)} test completed."
    case_match = re.search(r"--case-version\s+([A-Za-z0-9_.-]+)", haystack)
    if case_match:
        return f"{op} {case_match.group(1)} ready."
    return f"{op} work ready."


